SELECT
    sl.SAILING_ID,
    sl.TIME_CREATED,
    sl.EVENT_TYPE,
    sl.MILE_MARKER_ID,
    sl.ETA
FROM EDPPROD.EDP_SOURCE.WEBATDS_STATUSLOG sl
WHERE sl.SAILING_ID = %(leg_id)s
  AND sl.TIME_CREATED >= COALESCE(%(departure_anchor)s::TIMESTAMP_TZ, DATEADD(hour, -96, CURRENT_TIMESTAMP()))
  AND sl.TIME_CREATED <= CURRENT_TIMESTAMP()
ORDER BY sl.TIME_CREATED
