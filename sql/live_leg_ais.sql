WITH sailing_mmsi AS (
    SELECT DISTINCT tug.MMSI
    FROM EDPPROD.EDP_SOURCE.WEBATDS_SAILINGASSET sa
    INNER JOIN EDPPROD.EDP_SOURCE.WEBATDS_TUG tug
        ON tug.COMPANYASSET_PTR_ID = sa.ASSET_ID
    WHERE sa.RELATED_SAILING_ID = %(leg_id)s
      AND tug.MMSI IS NOT NULL
)
SELECT
    ha.TIMESTAMP,
    ha.SPEED,
    ha.NAV_STATUS_CODE,
    ha.INFERRED_NUM_BARGES,
    ha.AIS_ETA,
    ha.OPENTUG_ETA
FROM sailing_mmsi sm
INNER JOIN EDPPROD.EDP_SOURCE.WEBATDS_HISTORICALAIS ha
    ON ha.MMSI = sm.MMSI
WHERE ha.TIMESTAMP >= COALESCE(GREATEST(%(departure_anchor)s::TIMESTAMP_TZ, DATEADD(hour, -96, CURRENT_TIMESTAMP())), DATEADD(hour, -96, CURRENT_TIMESTAMP()))
  AND ha.TIMESTAMP <= CURRENT_TIMESTAMP()
  AND ha.SPEED BETWEEN 0 AND 30
ORDER BY ha.TIMESTAMP
